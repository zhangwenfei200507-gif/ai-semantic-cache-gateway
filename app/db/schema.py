from __future__ import annotations

import hashlib
import threading
from datetime import datetime, timezone
from typing import Any

from app.db.postgres import direct_connection


SCHEMA_VERSION = 4
SCHEMA_NAME = "004_oauth_authentication"

# Schema validation is immutable for the lifetime of one application process.
# Re-checking it for every authenticated request creates a fresh PostgreSQL
# connection during Railway cold starts and makes concurrent page loads queue.
_schema_verified = False
_schema_lock = threading.Lock()

SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    checksum TEXT NOT NULL,
    applied_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS migration_runs (
    run_id TEXT PRIMARY KEY,
    source_auth_sha256 TEXT NOT NULL,
    source_history_sha256 TEXT NOT NULL,
    status TEXT NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at TEXT NOT NULL,
    completed_at TEXT
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    password_hash TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_verified BOOLEAN NOT NULL DEFAULT TRUE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_lower ON users (LOWER(email));

-- OAuth is the only supported login path. Keep users/workspaces stable so
-- existing business data remains attached when an identity is linked.
CREATE TABLE IF NOT EXISTS oauth_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider TEXT NOT NULL,
    provider_subject TEXT NOT NULL,
    email TEXT NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TEXT NOT NULL,
    last_login_at TEXT NOT NULL,
    UNIQUE(provider, provider_subject),
    UNIQUE(provider, user_id)
);
CREATE INDEX IF NOT EXISTS idx_oauth_accounts_user ON oauth_accounts(user_id);
CREATE INDEX IF NOT EXISTS idx_oauth_accounts_email ON oauth_accounts(LOWER(email));

CREATE TABLE IF NOT EXISTS workspaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    name TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'personal',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_workspaces_owner ON workspaces(owner_user_id);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
          AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'workspaces'
          AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE workspaces ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
          AND column_name = 'password_hash'
    ) THEN
        ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
        ALTER TABLE users ALTER COLUMN is_verified SET DEFAULT TRUE;
    END IF;
END $$;

-- The old password/email-verification implementation is retired. Existing
-- user rows are retained for Workspace and history ownership; old credentials
-- and reset/verification tokens are removed by this idempotent migration.
UPDATE users
SET password_hash = NULL,
    is_verified = TRUE,
    updated_at = updated_at;
DROP TABLE IF EXISTS email_verification_tokens;
DROP TABLE IF EXISTS password_reset_tokens;

CREATE TABLE IF NOT EXISTS workspace_members (
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'owner',
    created_at TEXT NOT NULL,
    PRIMARY KEY (workspace_id, user_id)
);

CREATE TABLE IF NOT EXISTS workspace_settings (
    workspace_id BIGINT PRIMARY KEY REFERENCES workspaces(id) ON DELETE CASCADE,
    settings_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    version INTEGER NOT NULL DEFAULT 1,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT REFERENCES workspaces(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    display_name TEXT NOT NULL,
    provider_type TEXT NOT NULL DEFAULT 'openai_compatible',
    base_url TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'answer',
    status TEXT NOT NULL DEFAULT 'configured',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    default_model TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_providers_workspace ON providers(workspace_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_providers_workspace_name
    ON providers(workspace_id, name)
    WHERE workspace_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS provider_models (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
    model_id TEXT NOT NULL,
    modality TEXT NOT NULL DEFAULT 'text',
    context_window INTEGER,
    supports_streaming BOOLEAN NOT NULL DEFAULT FALSE,
    input_price_per_million NUMERIC(20,10),
    output_price_per_million NUMERIC(20,10),
    image_price NUMERIC(20,10),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE(provider_id, model_id)
);

CREATE TABLE IF NOT EXISTS provider_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL REFERENCES providers(id) ON DELETE CASCADE,
    key_version TEXT,
    encrypted_api_key TEXT,
    key_fingerprint TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE(provider_id)
);

-- Stage 3 allows a provider to use separate credentials for separate models.
ALTER TABLE provider_credentials
    DROP CONSTRAINT IF EXISTS provider_credentials_provider_id_key;
ALTER TABLE provider_credentials
    ADD COLUMN IF NOT EXISTS provider_model_id BIGINT
        REFERENCES provider_models(id) ON DELETE CASCADE;
ALTER TABLE provider_credentials
    ADD COLUMN IF NOT EXISTS verified_at TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_provider_credentials_provider
    ON provider_credentials(provider_id)
    WHERE provider_model_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_provider_credentials_model
    ON provider_credentials(provider_id, provider_model_id)
    WHERE provider_model_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS gateway_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id TEXT NOT NULL UNIQUE,
    user_id TEXT,
    workspace_id BIGINT REFERENCES workspaces(id) ON DELETE SET NULL,
    legacy_user_id TEXT,
    provider TEXT,
    model TEXT,
    question TEXT,
    answer TEXT,
    cache_hit BOOLEAN NOT NULL DEFAULT FALSE,
    cache_type TEXT,
    similarity DOUBLE PRECISION,
    threshold DOUBLE PRECISION,
    prompt_tokens BIGINT NOT NULL DEFAULT 0,
    completion_tokens BIGINT NOT NULL DEFAULT 0,
    total_tokens BIGINT NOT NULL DEFAULT 0,
    cost NUMERIC(28,12) NOT NULL DEFAULT 0,
    saved_cost NUMERIC(28,12) NOT NULL DEFAULT 0,
    latency_ms DOUBLE PRECISION NOT NULL DEFAULT 0,
    provider_latency_ms DOUBLE PRECISION NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'success',
    error TEXT,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_gateway_history_workspace ON gateway_history(workspace_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_gateway_history_user ON gateway_history(user_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_gateway_history_created ON gateway_history(created_at);

CREATE TABLE IF NOT EXISTS legacy_user_mapping (
    legacy_value TEXT PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    workspace_id BIGINT REFERENCES workspaces(id) ON DELETE SET NULL,
    match_type TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS legacy_unassigned_records (
    request_id TEXT PRIMARY KEY REFERENCES gateway_history(request_id) ON DELETE CASCADE,
    raw_user_id TEXT,
    reason TEXT NOT NULL,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS image_assets (
    id TEXT PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    request_id TEXT,
    conversation_id TEXT,
    image_index INTEGER NOT NULL DEFAULT 0,
    storage_backend TEXT NOT NULL,
    object_key TEXT NOT NULL,
    mime_type TEXT NOT NULL,
    file_size BIGINT NOT NULL,
    width INTEGER,
    height INTEGER,
    content_sha256 TEXT,
    status TEXT NOT NULL DEFAULT 'ready',
    error TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE(workspace_id, request_id, image_index)
);
CREATE INDEX IF NOT EXISTS idx_image_assets_workspace_created
    ON image_assets(workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_image_assets_request
    ON image_assets(workspace_id, request_id);
"""


def schema_checksum() -> str:
    return hashlib.sha256(SCHEMA_SQL.encode("utf-8")).hexdigest()


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def apply_schema(database_url: str, *, dry_run: bool = False) -> dict[str, Any]:
    global _schema_verified
    checksum = schema_checksum()
    with direct_connection(database_url) as conn:
        if dry_run:
            row = conn.execute(
                "SELECT version, name, checksum FROM schema_migrations WHERE version = %s",
                (SCHEMA_VERSION,),
            ).fetchone() if _table_exists(conn, "schema_migrations") else None
            conn.rollback()
            return {
                "version": SCHEMA_VERSION,
                "name": SCHEMA_NAME,
                "checksum": checksum,
                "already_applied": bool(row),
                "target_has_schema": bool(row),
            }

        conn.execute(SCHEMA_SQL)
        existing = conn.execute(
            "SELECT checksum FROM schema_migrations WHERE version = %s",
            (SCHEMA_VERSION,),
        ).fetchone()
        if existing and existing["checksum"] != checksum:
            raise RuntimeError(
                f"PostgreSQL schema checksum mismatch for migration {SCHEMA_NAME}"
            )
        if not existing:
            conn.execute(
                "INSERT INTO schema_migrations(version, name, checksum, applied_at) VALUES(%s, %s, %s, %s)",
                (SCHEMA_VERSION, SCHEMA_NAME, checksum, _now()),
            )
        conn.commit()
        with _schema_lock:
            _schema_verified = True
        return {
            "version": SCHEMA_VERSION,
            "name": SCHEMA_NAME,
            "checksum": checksum,
            "already_applied": bool(existing),
        }


def _table_exists(conn, table: str) -> bool:
    row = conn.execute(
        "SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = %s",
        (table,),
    ).fetchone()
    return bool(row)


def require_schema() -> None:
    global _schema_verified
    from app.config.settings import settings

    if _schema_verified:
        return

    with _schema_lock:
        if _schema_verified:
            return

        with direct_connection(str(settings.database_url)) as conn:
            row = conn.execute(
                "SELECT version, checksum FROM schema_migrations WHERE version = %s",
                (SCHEMA_VERSION,),
            ).fetchone()
            if not row:
                raise RuntimeError(
                    "PostgreSQL schema is not initialized; run the migration command before starting the app"
                )
            if row["checksum"] != schema_checksum():
                raise RuntimeError("PostgreSQL schema checksum mismatch")

        _schema_verified = True


